"""Writes tests/fixtures/cup-rules.json: league.roster_allowed() answers for every scheduled (cup, CP) on a fixed sample
of species, the shared fixture for the Python rule evaluator and its JS port (includes/pro/observed-weights.js).

    python3 -I web/scripts/yt-harvest/cup_rule_fixtures.py          # rewrite the fixture
    python3 -I web/scripts/yt-harvest/cup_rule_fixtures.py --check  # full parity input: every species, stdout
"""
import hashlib
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import league  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / 'tests/fixtures/cup-rules.json'
EDGE = ['bulbasaur', 'ivysaur', 'venusaur', 'venusaur_mega', 'venusaur_shadow', 'medicham', 'azumarill', 'bidoof',
        'bidoof_shadow', 'mewtwo_mega_x', 'kyogre_primal', 'pikachu', 'raichu_alolan', 'marowak_alolan_shadow', 'shuckle',
        'smeargle', 'meltan', 'registeel', 'deoxys_defense', 'lapras_shadow', 'galvantula', 'cradily', 'umbreon',
        'clodsire', 'tinkaton', 'charizard_mega_y', 'skarmory_shadow', 'chansey', 'carbink', 'feraligatr_shadow']


def formats(schedule):
    seen = []
    for p in schedule.get('periods', []):
        for f in p.get('formats', []):
            cp = f.get('cp') or (schedule['cups'].get(f['id']) or {}).get('cp')
            if f.get('id') in schedule['cups'] and cp and (f['id'], cp) not in seen:
                seen.append((f['id'], cp))
    return seen


def answer(schedule, gm, cup_id, cp, sid):
    cup = dict(schedule['cups'][cup_id], cp=cp)
    mon = gm.get(sid) or gm.get(sid.removesuffix('_shadow'))
    return league.roster_allowed(cup_id, cup, sid, mon, gm)


def build(sample=6):
    schedule, gm = league.load_schedule(), league.load_gamemaster()
    ids = sorted(gm)
    cases = []
    for cup_id, cp in formats(schedule):
        ranked = sorted(ids, key=lambda s: hashlib.sha256(f'{cup_id}@{cp}:{s}'.encode()).hexdigest())
        yes = [s for s in ranked if answer(schedule, gm, cup_id, cp, s) is True][:sample]
        no = [s for s in ranked if answer(schedule, gm, cup_id, cp, s) is False][:sample]
        for sid in sorted(set(yes + no + [e for e in EDGE if e in gm])):
            cases.append([cup_id, cp, sid, answer(schedule, gm, cup_id, cp, sid)])
    return {'note': 'Generated by scripts/yt-harvest/cup_rule_fixtures.py from data/gbl-schedule.json and '
                    'includes/pro/data/gamemaster.json; [cupId, cp, speciesId, roster_allowed].', 'cases': cases}


if __name__ == '__main__':
    if '--check' in sys.argv:
        schedule, gm = league.load_schedule(), league.load_gamemaster()
        json.dump([[c, cp, s, answer(schedule, gm, c, cp, s)] for c, cp in formats(schedule) for s in sorted(gm)], sys.stdout)
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(json.dumps(build(), separators=(',', ':')) + '\n', encoding='utf-8')
        print(OUT, len(json.loads(OUT.read_text())['cases']), 'cases')
